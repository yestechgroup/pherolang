#!/usr/bin/env node
// Validate the generated editor grammar package with Shiki and compare its
// lexical scopes to the compiler-backed highlight goldens.
//
// This script is deliberately read-only: it loads the committed files under
// `site/packages/highlighting`, tokenizes every `examples/support/support.*`
// source, pins the representative scopes, and reports the expected
// TextMate-vs-compiler divergence (contextual words that need parser state,
// and compiler semantic refinements). Regenerate the package with
// `pherolang grammar --out site/packages/highlighting`; a hand edit fails the
// Rust byte-comparison test as well.
//
// Usage: node site/scripts/check-grammars.mjs

import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createHighlighter } from 'shiki';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const siteDir = join(root, 'site');
const packageDir = join(siteDir, 'packages/highlighting');

const KEYWORD = 'keyword.control.pherolang';
const failures = [];
const contextualDivergence = new Map();
const semanticRefinements = new Map();

function check(condition, message) {
  if (!condition) failures.push(message);
}

function readJson(path) {
  check(existsSync(path), `missing generated file: ${path}`);
  if (!existsSync(path)) return undefined;
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    failures.push(`invalid JSON in ${path}: ${error.message}`);
    return undefined;
  }
}

function wordsFromRule(pattern) {
  if (typeof pattern !== 'string') return new Set();
  const start = pattern.indexOf('(?:');
  if (start === -1) return new Set();
  const end = pattern.indexOf(')', start + 3);
  if (end === -1) return new Set();
  return new Set(
    pattern
      .slice(start + 3, end)
      .split('|')
      .map((word) => word.replaceAll('\\', '')),
  );
}

function wordsFor(grammar, key) {
  const rule = grammar?.repository?.[key]?.patterns?.[0];
  return rule ? wordsFromRule(rule.match) : new Set();
}

function isInsideCommentOrString(token) {
  return token.scopes.some(
    (scope) => scope.startsWith('comment.') || scope.startsWith('string.'),
  );
}

/** Maps a byte offset in the UTF-8 source to a JavaScript (UTF-16) index. */
function byteIndexMap(source) {
  const encoder = new TextEncoder();
  const total = encoder.encode(source).length;
  const map = new Int32Array(total + 1);
  let byte = 0;
  for (let index = 0; index < source.length; ) {
    const codePoint = source.codePointAt(index);
    const units = codePoint > 0xffff ? 2 : 1;
    const bytes = encoder.encode(String.fromCodePoint(codePoint)).length;
    for (let offset = 0; offset < bytes; offset += 1) {
      map[byte + offset] = index;
    }
    byte += bytes;
    index += units;
  }
  map[total] = source.length;
  return map;
}

function record(map, surface, word, count = 1) {
  const key = `${surface}:${word}`;
  map.set(key, (map.get(key) ?? 0) + count);
}

function formatReport(map) {
  return [...map.entries()]
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([key, count]) => `  ${key}${count > 1 ? ` (${count})` : ''}`)
    .join('\n');
}

// --- load the catalogue and the generated package ---------------------------

const catalogue = readJson(join(siteDir, 'data/surfaces.json'));
if (!catalogue) {
  console.error('Cannot read site/data/surfaces.json.');
  process.exit(1);
}

const surfaces = catalogue.surfaces;
check(surfaces.length === 9, `site/data/surfaces.json lists ${surfaces.length} surfaces, expected 9`);

const loaded = [];
for (const surface of surfaces) {
  const { id, extension } = surface;
  const grammarPath = join(packageDir, 'grammars', `${id}.tmLanguage.json`);
  const configurationPath = join(packageDir, 'language-configurations', `${id}.json`);
  const grammar = readJson(grammarPath);
  const configuration = readJson(configurationPath);
  if (!grammar || !configuration) continue;

  check(grammar.formatVersion === 1, `${id}: grammar formatVersion`);
  check(grammar.name === id, `${id}: grammar name`);
  check(grammar.scopeName === `source.${id}`, `${id}: grammar scopeName`);
  check(
    Array.isArray(grammar.fileTypes) && grammar.fileTypes.includes(extension),
    `${id}: grammar fileTypes must include ${extension}`,
  );
  check(Array.isArray(grammar.aliases) && grammar.aliases.includes(id), `${id}: grammar aliases`);
  check(
    typeof grammar.comment === 'string' &&
      grammar.comment.includes('Generated by pherolang') &&
      grammar.comment.includes('do not edit'),
    `${id}: grammar generated header`,
  );
  check(
    Array.isArray(grammar.patterns) && grammar.patterns.length > 0,
    `${id}: grammar patterns`,
  );
  check(
    grammar.repository && Object.keys(grammar.repository).length > 0,
    `${id}: grammar repository`,
  );

  check(configuration.formatVersion === 1, `${id}: configuration formatVersion`);
  check(
    typeof configuration.comment === 'string' &&
      configuration.comment.includes('do not edit'),
    `${id}: configuration generated header`,
  );
  check(configuration.comments?.lineComment === '//', `${id}: line comment marker`);
  if (id === 'ifml') {
    check(!configuration.comments?.blockComment, 'ifml: no block comments');
  } else {
    check(
      Array.isArray(configuration.comments?.blockComment) &&
        configuration.comments.blockComment[0] === '/*' &&
        configuration.comments.blockComment[1] === '*/',
      `${id}: block comment markers`,
    );
  }
  for (const [open, close] of [
    ['{', '}'],
    ['[', ']'],
    ['(', ')'],
  ]) {
    check(
      configuration.brackets?.some((pair) => pair[0] === open && pair[1] === close),
      `${id}: bracket pair ${open}${close}`,
    );
    check(
      configuration.autoClosingPairs?.some((pair) => pair.open === open && pair.close === close),
      `${id}: auto-closing pair ${open}${close}`,
    );
    check(
      configuration.surroundingPairs?.some((pair) => pair.open === open && pair.close === close),
      `${id}: surrounding pair ${open}${close}`,
    );
  }
  check(
    configuration.autoClosingPairs?.some(
      (pair) => pair.open === '"' && pair.close === '"' && pair.notIn?.includes('string'),
    ),
    `${id}: string auto-closing pair`,
  );
  check(typeof configuration.wordPattern === 'string', `${id}: wordPattern`);
  check(!configuration.indentationRules, `${id}: no untested indentation rules`);

  check(!JSON.stringify(grammar).includes('/home/'), `${id}: grammar embeds an absolute path`);
  check(!JSON.stringify(grammar).includes('C:\\'), `${id}: grammar embeds an absolute path`);
  check(!JSON.stringify(configuration).includes('/home/'), `${id}: configuration embeds a path`);

  loaded.push({
    surface,
    grammar,
    configuration,
    keywordWords: wordsFor(grammar, 'keywords'),
    contextualWords: wordsFor(grammar, 'contextualWords'),
  });
}

if (failures.length > 0) {
  console.error('Generated grammar package shape failures:');
  for (const failure of failures) console.error(`  - ${failure}`);
  process.exit(1);
}

// --- load every grammar in Shiki --------------------------------------------

let highlighter;
try {
  highlighter = await createHighlighter({
    themes: ['github-light'],
    langs: loaded.map(({ surface, grammar }) => {
      // The committed grammar carries `aliases: ["<id>"]` (the issue's
      // required shape). Shiki treats an alias identical to the language name
      // as a circular alias, so drop it for the loader only; the file itself
      // is unchanged.
      const { aliases: _aliases, ...registration } = grammar;
      return { ...registration, displayName: surface.name };
    }),
  });
} catch (error) {
  console.error('Shiki failed to load a generated grammar:');
  console.error(error);
  process.exit(1);
}

for (const entry of loaded) {
  const { id, extension } = entry.surface;
  const example = join(root, 'examples/support', `support.${extension.slice(1)}`);
  check(existsSync(example), `${id}: missing example ${example}`);
  if (!existsSync(example)) continue;

  const source = readFileSync(example, 'utf8');
  let lines;
  try {
    lines = highlighter.codeToTokensBase(source, {
      lang: id,
      theme: 'github-light',
      includeExplanation: true,
    });
  } catch (error) {
    failures.push(`${id}: Shiki tokenization failed: ${error.message}`);
    continue;
  }

  const tokens = [];
  for (const line of lines) {
    for (const token of line) {
      const scopes = (token.explanation ?? []).flatMap((explanation) =>
        explanation.scopes.map((scope) => scope.scopeName),
      );
      tokens.push({
        start: token.offset,
        end: token.offset + token.content.length,
        content: token.content,
        scopes,
        scope: scopes.at(-1) ?? '',
      });
    }
  }

  Object.assign(entry, { source, tokens });

  // Compare generated lexical scopes to the committed compiler artifact.
  const artifactPath = join(root, 'tests/highlight/json', `support.${id}.json`);
  const artifact = readJson(artifactPath);
  if (!artifact) continue;
  const byteToIndex = byteIndexMap(source);
  const spans = artifact.spans.map((span) => ({
    ...span,
    jsStart: byteToIndex[span.start],
    jsEnd: byteToIndex[span.end],
  }));

  // Every compiler keyword span must be keyword-scoped, unless the word is a
  // contextual word that needs parser state (a pair rule) the grammar cannot
  // see. Real lexer keywords are never allowed to be missed.
  for (const span of spans) {
    if (span.class !== 'keyword') continue;
    const word = source.slice(span.jsStart, span.jsEnd);
    const overlapping = tokens.filter(
      (token) => token.start < span.jsEnd && token.end > span.jsStart,
    );
    if (overlapping.some((token) => token.scope === KEYWORD)) continue;

    const lineStart =
      source.slice(source.lastIndexOf('\n', span.jsStart - 1) + 1, span.jsStart).trim() === '';
    if (!entry.contextualWords.has(word)) {
      failures.push(`${id}: compiler keyword \`${word}\` is not keyword-scoped`);
    } else if (lineStart) {
      failures.push(`${id}: line-start contextual \`${word}\` is not keyword-scoped`);
    } else {
      record(contextualDivergence, id, word);
    }
  }

  // A grammar keyword span must have a compiler span. The compiler may refine
  // a lexical keyword into a declaration, a function, a property, or an
  // annotation in the semantic pass; that is a documented refinement, not a
  // lexical miss. A keyword inside a comment, string, or punctuation span
  // would be a real ordering bug.
  for (const token of tokens) {
    if (token.scope !== KEYWORD || token.content.trim() === '') continue;
    const span = spans.find(
      (candidate) => candidate.jsStart <= token.start && token.start < candidate.jsEnd,
    );
    if (!span) {
      failures.push(`${id}: grammar keyword \`${token.content}\` has no compiler span`);
    } else if (span.class !== 'keyword') {
      if (['comment', 'string', 'punctuation', 'operator', 'error'].includes(span.class)) {
        failures.push(
          `${id}: grammar keyword \`${token.content}\` is compiler \`${span.class}\``,
        );
      } else {
        record(semanticRefinements, id, `${token.content}→${span.class}`);
      }
    }
  }
}

// --- representative scope pins ---------------------------------------------

const wordPins = [
  ['mox', 'package', KEYWORD],
  ['mox', 'class', KEYWORD],
  ['actor', 'actor', KEYWORD],
  ['evt', 'event', KEYWORD],
  ['dmn', 'decision_model', KEYWORD],
  ['uc', 'usecase', KEYWORD],
  ['cmmn', 'case', KEYWORD],
  ['ifml', 'view', KEYWORD],
  ['deploy', 'component', KEYWORD],
  ['deploy', 'deployment', KEYWORD],
  ['mox', 'String', 'support.type.pherolang'],
  ['mox', 'Ticket', 'entity.name.type.pherolang'],
  ['ifml', 'true', 'constant.language.pherolang'],
  ['actor', '@why', 'entity.name.function.decorator.pherolang'],
];

for (const [id, word, scope] of wordPins) {
  const entry = loaded.find((candidate) => candidate.surface.id === id);
  check(entry !== undefined, `${id}: surface not loaded`);
  if (!entry) continue;
  check(
    Array.isArray(entry.tokens),
    `${id}: example was not tokenized (see the tokenization failure above)`,
  );
  if (!Array.isArray(entry.tokens)) continue;
  const matches = entry.tokens.filter(
    (token) => token.content === word && !isInsideCommentOrString(token),
  );
  check(matches.length > 0, `${id}: example has no \`${word}\` token`);
  for (const token of matches) {
    check(
      token.scope === scope,
      `${id}: \`${word}\` is scoped \`${token.scope}\`, expected \`${scope}\``,
    );
  }
}

// Shiki merges adjacent same-scope tokens (a brace can share a token with the
// whitespace before it), so punctuation/operator/string pins are asserted at a
// source offset rather than by exact token content.
const offsetPins = [
  ['mox', '"open"', 'string.quoted.double.pherolang'],
  ['mox', '{', 'punctuation.pherolang'],
  ['mox', '0', 'constant.numeric.pherolang'],
  ['deploy', '->', 'keyword.operator.pherolang'],
];

for (const [id, literal, scope] of offsetPins) {
  const entry = loaded.find((candidate) => candidate.surface.id === id);
  check(entry !== undefined, `${id}: surface not loaded`);
  if (!entry || !Array.isArray(entry.tokens)) continue;
  const index = entry.source.indexOf(literal);
  check(index >= 0, `${id}: example has no \`${literal}\``);
  if (index < 0) continue;
  const token = entry.tokens.find(
    (candidate) => candidate.start <= index && index < candidate.end,
  );
  check(token !== undefined, `${id}: no token covers \`${literal}\``);
  if (!token) continue;
  check(
    token.scope === scope,
    `${id}: \`${literal}\` is scoped \`${token.scope}\`, expected \`${scope}\``,
  );
}

// Pin the declaration name each representative word introduces. The Rust test
// pins the generated capture rule; this proves Shiki applies it to the real
// support corpus (including the quoted `.ifml` names).
const namePins = [
  ['mox', 'class', 'entity.name.type.pherolang'],
  ['actor', 'actor', 'entity.name.type.pherolang'],
  ['evt', 'event', 'entity.name.type.pherolang'],
  ['dmn', 'decision_model', 'entity.name.namespace.pherolang'],
  ['uc', 'usecase', 'entity.name.function.pherolang'],
  ['cmmn', 'case', 'entity.name.namespace.pherolang'],
  ['ifml', 'view', 'entity.name.type.pherolang'],
  ['deploy', 'component', 'entity.name.type.pherolang'],
  ['deploy', 'deployment', 'entity.name.function.pherolang'],
];

for (const [id, word, scope] of namePins) {
  const entry = loaded.find((candidate) => candidate.surface.id === id);
  if (!entry || !Array.isArray(entry.tokens)) continue;
  const index = entry.tokens.findIndex(
    (token) => token.content === word && !isInsideCommentOrString(token),
  );
  check(index >= 0, `${id}: example has no \`${word}\` declaration`);
  if (index < 0) continue;
  const name = entry.tokens.slice(index + 1).find((token) => token.content.trim() !== '');
  check(name !== undefined, `${id}: no declaration name after \`${word}\``);
  if (!name) continue;
  check(
    name.scope === scope,
    `${id}: name after \`${word}\` is scoped \`${name.scope}\`, expected \`${scope}\``,
  );
}

// --- report ----------------------------------------------------------------

if (contextualDivergence.size > 0) {
  console.log('Expected contextual divergence (TextMate is lexical-only; the compiler upgrades');
  console.log('these pair-position words at parse time):');
  console.log(formatReport(contextualDivergence));
}
if (semanticRefinements.size > 0) {
  console.log('Expected semantic refinements (the compiler refines a lexical word into a');
  console.log('declaration/property/function/annotation position):');
  console.log(formatReport(semanticRefinements));
}

if (failures.length > 0) {
  console.error(`Grammar validation failed with ${failures.length} finding(s):`);
  for (const failure of failures) console.error(`  - ${failure}`);
  process.exit(1);
}

console.log(
  `OK: ${loaded.length} generated grammars and language configurations load in Shiki and ` +
    `tokenize examples/support/* with the pinned scopes.`,
);
