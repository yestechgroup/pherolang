    fn alternation_is_longest_first_then_alphabetical() {
        let pattern = alternation(&["actor", "actors", "agent"]).expect("non-empty");
        assert_eq!(pattern, "(?:actors|actor|agent)");
    }

    #[test]
    fn alternation_escapes_non_identifier_characters() {
        assert_eq!(escape_literal("a.b"), r"a\.b");
    }

    #[test]
    fn generation_is_deterministic_and_names_every_surface() {
        let first = generate_grammars();
        let second = generate_grammars();
        assert_eq!(first, second);
        assert_eq!(first.len(), 1 + Surface::ALL.len() * 2);
        for surface in Surface::ALL {
            assert!(first.iter().any(|file| file.path == grammar_path(surface)));
            assert!(first
                .iter()
                .any(|file| file.path == configuration_path(surface)));
        }
    }

    #[test]
    fn every_generated_file_carries_the_header() {
        for file in generate_grammars() {
            assert!(
                file.contents.contains("Generated by pherolang"),
                "{} is missing the generated header",
                file.path
            );
            assert!(
                file.contents.contains("do not edit"),
                "{} is missing the do-not-edit marker",
                file.path
            );
        }
    }
