//! Generated TextMate grammars and editor language configurations.
//!
//! The generator derives every rule from [`crate::metadata`] — the real lexer
//! keywords, contextual words, literals, builtin types, declaration table and
//! scope mapping — and from the surface's lexer family. There is **no second
//! vocabulary** here: a keyword added to `phero_syntax::words` appears in the
//! next generated grammar, and the committed files are byte-checked by
//! `crates/phero-highlight/tests/grammar.rs`.
//!
//! # What TextMate can and cannot express
//!
//! TextMate grammars are regular expressions over one line at a time. They
//! can recognize the lexical layer — keywords, literals, builtin types, the
//! capitalized type-name heuristic, strings, escapes, comments, numbers,
//! punctuation and operators — but they cannot run the parser. Contextual
//! words are therefore lexical-only: a contextual word is scoped as a keyword
//! when it starts a line (the same cheap positional rule the compiler's
//! contextual pass uses), and stays an ordinary identifier elsewhere. Pair
//! rules (`inject decision`, `first then`, …) and semantic refinements that
//! turn a lexical word into a declaration position are compiler-only; the
//! generated grammar deliberately does not guess at them.
//! `docs/HIGHLIGHTING.md` owns the limitation list.
//!
//! # Determinism
//!
//! The output is a sorted, versioned, camelCase JSON document per surface plus
//! a package manifest. It contains no colour, timestamp, host, or absolute
//! path; two runs are byte-identical. The header names the regeneration
//! command, and [`check_grammars`] reports a missing, stale, or unexpected
//! file — so a hand edit fails instead of drifting.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::io;
use std::path::Path;

use serde::Serialize;

use crate::class::{HighlightClass, HighlightModifier};
use crate::metadata::{class_scope, metadata_for, scope_for, LexerKind, SurfaceMetadata};
use crate::surface::Surface;

/// The generated-grammar package format version.
pub const GRAMMAR_FORMAT_VERSION: u32 = 1;

/// The package directory name under the canonical `site/packages/` location.
pub const PACKAGE_NAME: &str = "@pherolang/highlighting";

/// The generated package manifest's file name.
pub const PACKAGE_MANIFEST: &str = "package.json";

/// The grammar directory (relative to the package root).
pub const GRAMMARS_DIR: &str = "grammars";

/// The language-configuration directory (relative to the package root).
pub const LANGUAGE_CONFIGURATIONS_DIR: &str = "language-configurations";

/// The grammar file suffix, appended to the surface id.
pub const GRAMMAR_SUFFIX: &str = ".tmLanguage.json";

/// The language-configuration file suffix, appended to the surface id.
pub const CONFIGURATION_SUFFIX: &str = ".json";

/// The header every generated file carries.
pub const GENERATED_HEADER: &str = "Generated by pherolang from the phero-highlight \
     surface metadata; do not edit. Regenerate with \
     `pherolang grammar --out site/packages/highlighting`.";

/// One generated file, in canonical (sorted) order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    /// The package-relative POSIX path (`grammars/mox.tmLanguage.json`, …).
    pub path: String,
    /// The complete file contents, including the generated header.
    pub contents: String,
}

/// Why a committed grammar package does not match the generator.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GrammarProblemKind {
    /// A generated file is absent.
    Missing,
    /// A generated file's bytes differ from the generator's output.
    Stale,
    /// A grammar or configuration file exists that the generator does not
    /// produce (a stale surface, or a hand-added copy).
    Unexpected,
}

/// One mismatch between the committed package and the generator.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GrammarProblem {
    /// The package-relative POSIX path.
    pub path: String,
    /// What is wrong with it.
    pub kind: GrammarProblemKind,
}

impl fmt::Display for GrammarProblem {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.kind {
            GrammarProblemKind::Missing => write!(
                f,
                "missing generated file `{}` — run `pherolang grammar --out <dir>`",
                self.path
            ),
            GrammarProblemKind::Stale => write!(
                f,
                "stale generated file `{}` — run `pherolang grammar --out <dir>` \
                 and read the diff; never hand-edit it",
                self.path
            ),
            GrammarProblemKind::Unexpected => write!(
                f,
                "unexpected generated file `{}` — it is not one of the \
                 surfaces the generator writes; remove it or add the surface",
                self.path
            ),
        }
    }
}

impl std::error::Error for GrammarProblem {}

/// Generates every grammar, language configuration and the package manifest.
///
/// The result is deterministic and sorted by package-relative path.
#[must_use]
pub fn generate_grammars() -> Vec<GeneratedFile> {
    let mut files = Vec::with_capacity(1 + Surface::ALL.len() * 2);
    files.push(GeneratedFile {
        path: PACKAGE_MANIFEST.to_string(),
        contents: package_manifest(),
    });
    for surface in Surface::ALL {
        files.push(GeneratedFile {
            path: grammar_path(surface),
            contents: grammar_json(surface),
        });
    }
    for surface in Surface::ALL {
        files.push(GeneratedFile {
            path: configuration_path(surface),
            contents: configuration_json(surface),
        });
    }
    files.sort_by(|left, right| left.path.cmp(&right.path));
    files
}

/// The package-relative grammar path for a surface.
#[must_use]
pub fn grammar_path(surface: Surface) -> String {
    format!("{GRAMMARS_DIR}/{}{GRAMMAR_SUFFIX}", surface.id())
}

/// The package-relative language-configuration path for a surface.
#[must_use]
pub fn configuration_path(surface: Surface) -> String {
    format!(
        "{LANGUAGE_CONFIGURATIONS_DIR}/{}{CONFIGURATION_SUFFIX}",
        surface.id()
    )
}

/// Writes the generated package into `dir`, creating directories as needed.
///
/// Returns the package-relative paths written, sorted by path.
///
/// # Errors
///
/// Returns the underlying [`io::Error`] when a directory or file cannot be
/// created. Existing files are overwritten; unrelated files are left alone.
pub fn write_grammars(dir: &Path) -> io::Result<Vec<String>> {
    let files = generate_grammars();
    for file in &files {
        let path = dir.join(&file.path);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, &file.contents)?;
    }
    Ok(files.into_iter().map(|file| file.path).collect())
}

/// Checks that `dir` holds exactly the generated package, byte for byte.
///
/// # Errors
///
/// Returns one [`GrammarProblem`] per missing, stale, or unexpected grammar or
/// configuration file, sorted by path. A `README` or other non-generated file
/// is ignored.
pub fn check_grammars(dir: &Path) -> Result<(), Vec<GrammarProblem>> {
    let files = generate_grammars();
    let expected: BTreeSet<&str> = files.iter().map(|file| file.path.as_str()).collect();
    let mut problems = Vec::new();

    for file in &files {
        let path = dir.join(&file.path);
        match std::fs::read_to_string(&path) {
            Ok(actual) if actual == file.contents => {}
            Ok(_) => problems.push(GrammarProblem {
                path: file.path.clone(),
                kind: GrammarProblemKind::Stale,
            }),
            Err(_) => problems.push(GrammarProblem {
                path: file.path.clone(),
                kind: GrammarProblemKind::Missing,
            }),
        }
    }

    for (directory, suffix) in [
        (GRAMMARS_DIR, GRAMMAR_SUFFIX),
        (LANGUAGE_CONFIGURATIONS_DIR, CONFIGURATION_SUFFIX),
    ] {
        let Ok(entries) = std::fs::read_dir(dir.join(directory)) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if !path.is_file() {
                continue;
            }
            let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
                continue;
            };
            if !name.ends_with(suffix) {
                continue;
            }
            let relative = format!("{directory}/{name}");
            if !expected.contains(relative.as_str()) {
                problems.push(GrammarProblem {
                    path: relative,
                    kind: GrammarProblemKind::Unexpected,
                });
            }
        }
    }

    problems.sort_by(|left, right| left.path.cmp(&right.path));
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems)
    }
}

// --- serialized shapes -------------------------------------------------------

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct Grammar {
    format_version: u32,
    comment: String,
    name: String,
    scope_name: String,
    file_types: Vec<String>,
    aliases: Vec<String>,
    patterns: Vec<Include>,
    repository: BTreeMap<String, RepositoryEntry>,
}

#[derive(Debug, Serialize)]
struct Include {
    include: String,
}

#[derive(Debug, Serialize)]
struct RepositoryEntry {
    patterns: Vec<Rule>,
}

#[derive(Debug, Default, Serialize)]
#[serde(rename_all = "camelCase")]
struct Rule {
    #[serde(skip_serializing_if = "Option::is_none")]
    name: Option<String>,
    #[serde(rename = "match", skip_serializing_if = "Option::is_none")]
    pattern: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    begin: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    end: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    captures: Option<BTreeMap<String, ScopedName>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    patterns: Option<Vec<Rule>>,
}

#[derive(Debug, Serialize)]
struct ScopedName {
    name: String,
}

impl Rule {
    fn scoped(name: &str, pattern: String) -> Self {
        Self {
            name: Some(name.to_string()),
            pattern: Some(pattern),
            ..Self::default()
        }
    }

    fn begin_end(name: &str, begin: &str, end: &str, patterns: Vec<Rule>) -> Self {
        Self {
            name: Some(name.to_string()),
            begin: Some(begin.to_string()),
            end: Some(end.to_string()),
            patterns: if patterns.is_empty() {
                None
            } else {
                Some(patterns)
            },
            ..Self::default()
        }
    }

    fn captured(pattern: String, captures: BTreeMap<String, ScopedName>) -> Self {
        Self {
            pattern: Some(pattern),
            captures: Some(captures),
            ..Self::default()
        }
    }
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct LanguageConfiguration {
    format_version: u32,
    comment: String,
    comments: Comments,
    brackets: Vec<[String; 2]>,
    auto_closing_pairs: Vec<AutoClosingPair>,
    surrounding_pairs: Vec<Pair>,
    word_pattern: String,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct Comments {
    line_comment: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    block_comment: Option<[String; 2]>,
}

#[derive(Debug, Serialize)]
struct Pair {
    open: String,
    close: String,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct AutoClosingPair {
    open: String,
    close: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    not_in: Option<Vec<String>>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct PackageManifest {
    name: &'static str,
    private: bool,
    description: &'static str,
    comment: &'static str,
    files: [&'static str; 2],
}

// --- grammar construction ----------------------------------------------------

/// The repository keys, in the order their `include`s appear at the top level.
const REPOSITORY_ORDER: &[&str] = &[
    "comments",
    "strings",
    "numbers",
    "annotations",
    "escapedIdentifiers",
    "declarations",
    "contextualWords",
    "literals",
    "keywords",
    "builtinTypes",
    "typeNames",
    "identifiers",
    "punctuation",
    "operators",
];

/// Declaration words that introduce a *reference* rather than a name. Their
/// own word is still keyword-scoped; only the following-name capture is
/// suppressed, because the next token is a path, a clause, or an existing
/// name — not a declaration.
const REFERENCE_ONLY_DECLARATIONS: &[&str] = &[
    "annotation",
    "connects",
    "defaults",
    "domain",
    "import",
    "inject",
    "inputs",
    "knowledge",
    "logic",
    "mappings",
    "output",
    "outputs",
    "publishes",
    "realizes",
    "target",
];

/// Declaration words whose name is a dotted namespace (`package a.b.c`).
const DOTTED_DECLARATIONS: &[&str] = &["base", "namespace", "package"];

fn package_manifest() -> String {
    let manifest = PackageManifest {
        name: PACKAGE_NAME,
        private: true,
        description: "Generated TextMate grammars and language configurations \
                      for the Phero Lang surfaces.",
        comment: GENERATED_HEADER,
        files: [GRAMMARS_DIR, LANGUAGE_CONFIGURATIONS_DIR],
    };
    to_json(&manifest)
}

fn grammar_json(surface: Surface) -> String {
    let metadata = metadata_for(surface);
    let repository = repository(metadata);
    let mut patterns = Vec::new();
    for key in REPOSITORY_ORDER {
        if repository.contains_key(*key) {
            patterns.push(Include {
                include: format!("#{key}"),
            });
        }
    }
    let grammar = Grammar {
        format_version: GRAMMAR_FORMAT_VERSION,
        comment: GENERATED_HEADER.to_string(),
        name: surface.id().to_string(),
        scope_name: format!("source.{}", surface.id()),
        file_types: vec![format!(".{}", surface.extension())],
        aliases: vec![surface.id().to_string()],
        patterns,
        repository,
    };
    to_json(&grammar)
}

fn configuration_json(surface: Surface) -> String {
    let metadata = metadata_for(surface);
    let word_pattern = if metadata.lexer == LexerKind::Ifml {
        r"(\d+(?:\.\d+)?)|([A-Za-z][A-Za-z0-9_]*)"
    } else {
        r"(-?\d+)|([A-Za-z_][A-Za-z0-9_]*)"
    };
    let mut auto_closing = vec![
        pair_rule("{", "}"),
        pair_rule("[", "]"),
        pair_rule("(", ")"),
    ];
    auto_closing.push(AutoClosingPair {
        open: "\"".to_string(),
        close: "\"".to_string(),
        not_in: Some(vec!["string".to_string(), "comment".to_string()]),
    });
    let configuration = LanguageConfiguration {
        format_version: GRAMMAR_FORMAT_VERSION,
        comment: GENERATED_HEADER.to_string(),
        comments: Comments {
            line_comment: "//".to_string(),
            block_comment: if metadata.lexer != LexerKind::Ifml {
                Some(["/*".to_string(), "*/".to_string()])
            } else {
                None
            },
        },
        brackets: vec![
            ["{".to_string(), "}".to_string()],
            ["[".to_string(), "]".to_string()],
            ["(".to_string(), ")".to_string()],
        ],
        auto_closing_pairs: auto_closing,
        surrounding_pairs: vec![
            surrounding_pair("{", "}"),
            surrounding_pair("[", "]"),
            surrounding_pair("(", ")"),
            surrounding_pair("\"", "\""),
        ],
        word_pattern: word_pattern.to_string(),
    };
    to_json(&configuration)
}

fn pair_rule(open: &str, close: &str) -> AutoClosingPair {
    AutoClosingPair {
        open: open.to_string(),
        close: close.to_string(),
        not_in: None,
    }
}

fn surrounding_pair(open: &str, close: &str) -> Pair {
    Pair {
        open: open.to_string(),
        close: close.to_string(),
    }
}

fn repository(metadata: &SurfaceMetadata) -> BTreeMap<String, RepositoryEntry> {
    let mut repository = BTreeMap::new();
    let mut insert = |key: &str, patterns: Vec<Rule>| {
        if !patterns.is_empty() {
            repository.insert(key.to_string(), RepositoryEntry { patterns });
        }
    };

    insert("comments", comment_rules(metadata));
    let mut strings = vec![string_rule(metadata)];
    if metadata.lexer == LexerKind::Rune {
        strings.push(single_quoted_string_rule());
    }
    insert("strings", strings);
    insert("numbers", vec![number_rule(metadata)]);
    insert("annotations", vec![annotation_rule()]);
    if metadata.lexer != LexerKind::Ifml {
        insert("escapedIdentifiers", escaped_identifier_rules());
    }
    insert("declarations", declaration_rules(metadata));
    insert(
        "contextualWords",
        contextual_line_start_rules(metadata).into_iter().collect(),
    );
    insert(
        "literals",
        word_rule(metadata.literals, class_scope(HighlightClass::Constant))
            .into_iter()
            .collect(),
    );
    insert(
        "keywords",
        word_rule(metadata.keywords, class_scope(HighlightClass::Keyword))
            .into_iter()
            .collect(),
    );
    insert(
        "builtinTypes",
        word_rule(
            metadata.builtin_types,
            scope_for(
                HighlightClass::Type,
                Some(HighlightModifier::DefaultLibrary),
            ),
        )
        .into_iter()
        .collect(),
    );
    insert("typeNames", vec![type_name_rule()]);
    insert("identifiers", vec![identifier_rule(metadata)]);
    insert("punctuation", vec![punctuation_rule()]);
    insert("operators", vec![operator_rule()]);
    repository
}

fn comment_rules(metadata: &SurfaceMetadata) -> Vec<Rule> {
    let documentation = scope_for(
        HighlightClass::Comment,
        Some(HighlightModifier::Documentation),
    );
    let comment = class_scope(HighlightClass::Comment);
    let mut rules = vec![Rule::scoped(documentation, r"///[^\n]*".to_string())];
    if metadata.lexer == LexerKind::MoxFamily {
        rules.push(Rule::begin_end(
            documentation,
            r"/\*\*(?!/)",
            r"\*/",
            Vec::new(),
        ));
    }
    rules.push(Rule::scoped(comment, r"//[^\n]*".to_string()));
    if metadata.lexer != LexerKind::Ifml {
        rules.push(Rule::begin_end(comment, r"/\*", r"\*/", Vec::new()));
    }
    rules
}

fn string_rule(metadata: &SurfaceMetadata) -> Rule {
    let escape = class_scope(HighlightClass::Escape);
    let mut patterns = vec![Rule::scoped(escape, r"\\u[0-9A-Fa-f]{4}".to_string())];
    let general = if metadata.lexer == LexerKind::Ifml {
        r#"\\["\\/bfnrt]"#
    } else {
        r"\\[\s\S]"
    };
    patterns.push(Rule::scoped(escape, general.to_string()));
    Rule::begin_end(class_scope(HighlightClass::String), "\"", "\"", patterns)
}

/// Rune also writes strings in single quotes.
fn single_quoted_string_rule() -> Rule {
    let escape = class_scope(HighlightClass::Escape);
    Rule::begin_end(
        class_scope(HighlightClass::String),
        "'",
        "'",
        vec![Rule::scoped(escape, r"\\[\s\S]".to_string())],
    )
}

fn number_rule(metadata: &SurfaceMetadata) -> Rule {
    let pattern = match metadata.lexer {
        LexerKind::Ifml => r"[0-9]+(?:\.[0-9]+)?",
        LexerKind::Rune => r"[0-9]*\.?[0-9]+(?:[eE][+-]?[0-9]+)?",
        LexerKind::MoxFamily => r"-?[0-9]+",
    };
    Rule::scoped(class_scope(HighlightClass::Number), pattern.to_string())
}

fn annotation_rule() -> Rule {
    Rule::scoped(
        class_scope(HighlightClass::Annotation),
        r"@[A-Za-z_][A-Za-z0-9_]*".to_string(),
    )
}

fn escaped_identifier_rules() -> Vec<Rule> {
    vec![
        Rule::scoped(
            class_scope(HighlightClass::Type),
            r"\^[A-Z][A-Za-z0-9_]*".to_string(),
        ),
        Rule::scoped(
            class_scope(HighlightClass::Variable),
            r"\^[a-z_][A-Za-z0-9_]*".to_string(),
        ),
    ]
}

fn type_name_rule() -> Rule {
    Rule::scoped(
        class_scope(HighlightClass::Type),
        r"\b[A-Z][A-Za-z0-9_]*\b".to_string(),
    )
}

fn identifier_rule(metadata: &SurfaceMetadata) -> Rule {
    let pattern = if metadata.lexer == LexerKind::Ifml {
        r"\b[a-z][A-Za-z0-9_]*\b"
    } else {
        r"\b[a-z_][A-Za-z0-9_]*\b"
    };
    Rule::scoped(class_scope(HighlightClass::Variable), pattern.to_string())
}

fn punctuation_rule() -> Rule {
    Rule::scoped(
        class_scope(HighlightClass::Punctuation),
        r"[{}()\[\],.;:]".to_string(),
    )
}

fn operator_rule() -> Rule {
    Rule::scoped(
        class_scope(HighlightClass::Operator),
        r"(?:->|=>|==|!=|<=|>=|~=|!~|&&|\|\||[=+\-*/%<>!&|^~?])".to_string(),
    )
}

fn word_rule(words: &[&str], name: &str) -> Option<Rule> {
    let alternation = alternation(words)?;
    Some(Rule::scoped(name, format!(r"\b{alternation}\b")))
}

fn contextual_line_start_rules(metadata: &SurfaceMetadata) -> Option<Rule> {
    if metadata.lexer == LexerKind::Ifml {
        return None;
    }
    let alternation = alternation(metadata.contextual)?;
    let mut captures = BTreeMap::new();
    captures.insert(
        "1".to_string(),
        ScopedName {
            name: class_scope(HighlightClass::Keyword).to_string(),
        },
    );
    Some(Rule::captured(
        format!(r"^[\t ]*({alternation})\b"),
        captures,
    ))
}

fn declaration_rules(metadata: &SurfaceMetadata) -> Vec<Rule> {
    let mut declarations: Vec<(&str, HighlightClass)> = metadata
        .declarations
        .iter()
        .copied()
        .filter(|(word, class)| {
            !REFERENCE_ONLY_DECLARATIONS.contains(word)
                && !matches!(class, HighlightClass::Keyword | HighlightClass::Annotation)
        })
        .collect();
    // Longest word first so a prefix never shadows a longer declaration word.
    declarations.sort_by(|left, right| {
        right
            .0
            .len()
            .cmp(&left.0.len())
            .then_with(|| left.0.cmp(right.0))
    });

    let atom = if metadata.lexer == LexerKind::Ifml {
        r#"(?:"(?:[^"\\\n\r]|\\.)*"|[A-Za-z][A-Za-z0-9_]*)"#
    } else {
        r"[A-Za-z_][A-Za-z0-9_]*"
    };

    declarations
        .into_iter()
        .map(|(word, class)| {
            let name = if DOTTED_DECLARATIONS.contains(&word) {
                format!(r"({atom}(?:\.{atom})*)")
            } else {
                format!(r"({atom})")
            };
            let mut captures = BTreeMap::new();
            captures.insert(
                "1".to_string(),
                ScopedName {
                    name: class_scope(HighlightClass::Keyword).to_string(),
                },
            );
            captures.insert(
                "2".to_string(),
                ScopedName {
                    name: class_scope(class).to_string(),
                },
            );
            Rule::captured(
                format!(r"^[\t ]*({})(?:\s+){name}", escape_literal(word)),
                captures,
            )
        })
        .collect()
}

/// Builds a deterministic `(?:longest|…)` alternation, or `None` when empty.
fn alternation(words: &[&str]) -> Option<String> {
    if words.is_empty() {
        return None;
    }
    let mut sorted = words.to_vec();
    sorted.sort_by(|left, right| right.len().cmp(&left.len()).then_with(|| left.cmp(right)));
    let mut pattern = String::from("(?:");
    for (index, word) in sorted.iter().enumerate() {
        if index > 0 {
            pattern.push('|');
        }
        pattern.push_str(&escape_literal(word));
    }
    pattern.push(')');
    Some(pattern)
}

/// Escapes a literal word for an Oniguruma pattern. Every vocabulary word is
/// identifier-shaped today, but the escape keeps the generator honest if one
/// ever is not.
fn escape_literal(word: &str) -> String {
    let mut escaped = String::with_capacity(word.len());
    for character in word.chars() {
        if character.is_ascii_alphanumeric() || character == '_' {
            escaped.push(character);
        } else {
            escaped.push('\\');
            escaped.push(character);
        }
    }
    escaped
}

fn to_json<T: Serialize>(value: &T) -> String {
    let mut json =
        serde_json::to_string_pretty(value).expect("the generated grammar shapes serialize");
    json.push('\n');
    json
}

