#!/usr/bin/env node
/**
 * Regenerate every committed byte under `site/data/` from the repository.
 *
 * The governing rule of this site: it is a *consumer* of the toolchain, not a
 * description of it. Nothing here is hand-written prose about the language —
 * every number, node, edge and artifact below is produced by the released
 * `pherolang` binary from `examples/`, and the CI `Site` workflow regenerates
 * the same files with the same released asset and fails on a diff.
 *
 * Inputs : examples/**, docs/**, crates/, tests/conformance/
 * Outputs: site/data/graph.json          the unified semantic graph (305 nodes)
 *          site/data/support-model.json  the demo projection (scripts/render-graph.mjs)
 *          site/data/artifacts/*.json    one compiled artifact per surface
 *          site/data/receipt.json        the committed verification receipt
 *          site/data/register.json       the proof-obligation register
 *          site/data/evidence.json       derived facts behind status.json
 *          site/data/docs-inventory.json the docs ingestion manifest
 *
 * Deterministic: identical inputs produce identical bytes. Never edit an
 * output by hand — change the source and rerun.
 *
 * Usage: node scripts/sync-model.mjs
 * Binary: $PHEROLANG_BIN, else site/.bin/pherolang (scripts/fetch-pherolang.mjs),
 *         else `pherolang` on PATH.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, statSync } from 'node:fs';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SURFACES } from './surfaces.mjs';

const SITE = dirname(dirname(fileURLToPath(import.meta.url)));
const ROOT = dirname(SITE);
const DATA = join(SITE, 'data');

const EXPECTED_VERSION = process.env.PHEROLANG_VERSION ?? '0.3.0';

const log = (message) => console.log(`sync-model: ${message}`);

function fail(message) {
  console.error(`sync-model: ${message}`);
  process.exit(1);
}

function posix(path) {
  return path.split(sep).join('/');
}

function rel(path) {
  return posix(relative(ROOT, path));
}

/** Resolve the binary: explicit env, then the fetched release, then PATH. */
function resolveBinary() {
  const candidates = [
    process.env.PHEROLANG_BIN,
    join(SITE, '.bin', process.platform === 'win32' ? 'pherolang.exe' : 'pherolang'),
  ].filter(Boolean);

  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate;
  }

  try {
    const found = execFileSync(process.platform === 'win32' ? 'where' : 'which', ['pherolang'], {
      encoding: 'utf8',
    })
      .split('\n')[0]
      .trim();
    if (found) return found;
  } catch {
    /* fall through to the error below */
  }

  fail(
    [
      'no `pherolang` binary found.',
      '  Run `node scripts/fetch-pherolang.mjs` to download the released binary,',
      '  or set PHEROLANG_BIN to a build you trust.',
      '  The site must be generated by a released binary: a workspace build would',
      '  make the committed data track unreleased DSL and defeat the freshness gate.',
    ].join('\n'),
  );
}

function run(binary, args, label) {
  try {
    return execFileSync(binary, args, {
      cwd: ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch (error) {
    const stderr = error.stderr?.toString?.() ?? '';
    fail(`${label} failed (exit ${error.status ?? '?'}):\n${stderr || error.message}`);
  }
}

async function writeJson(path, value) {
  await writeFile(path, `${JSON.stringify(value, null, 2)}\n`);
  log(`wrote ${rel(path)}`);
}

/** A file's presence and size, for the evidence report. */
function statOrNull(path) {
  const absolute = join(ROOT, path);
  if (!existsSync(absolute)) return { path, exists: false };
  const stats = statSync(absolute);
  return { path, exists: true, bytes: stats.size };
}

const binary = resolveBinary();
const reported = execFileSync(binary, ['--version'], { encoding: 'utf8' }).trim();
log(`using ${rel(binary)} — ${reported}`);

const reportedVersion = reported.split(/\s+/)[1] ?? 'unknown';
if (reportedVersion !== EXPECTED_VERSION) {
  console.warn(
    [
      '',
      `  WARNING: the binary reports ${reportedVersion} but the site is pinned to ${EXPECTED_VERSION}.`,
      '  The committed data would not match what CI regenerates from the released',
      '  asset, so the Site workflow would fail on its freshness diff.',
      '',
    ].join('\n'),
  );
}

await mkdir(join(DATA, 'artifacts'), { recursive: true });

// ---------------------------------------------------------------------------
// 1. The unified semantic graph — one artifact across every surface.
// ---------------------------------------------------------------------------
const graphPath = join(DATA, 'graph.json');
run(binary, ['graph', 'build', 'examples', '-o', graphPath], 'graph build');
log(`wrote ${rel(graphPath)}`);

const graph = JSON.parse(await readFile(graphPath, 'utf8'));

// ---------------------------------------------------------------------------
// 2. One compiled artifact per surface (for the artifact viewer and examples).
// ---------------------------------------------------------------------------
for (const surface of SURFACES) {
  const out = join(DATA, 'artifacts', `${surface.id}.json`);
  run(binary, ['ir', surface.example, '-o', out], `ir ${surface.example}`);
  log(`wrote ${rel(out)}`);
}

// ---------------------------------------------------------------------------
// 3. The verification receipt and the obligation register.
//    Both are committed goldens already gated by the Rust CI; copying them is
//    the honest move — regenerating the receipt would re-scope its closure.
// ---------------------------------------------------------------------------
const RECEIPT = 'examples/artifacts/support.receipt.json';
const REGISTER = 'docs/verification/register.json';

for (const [source, target] of [
  [RECEIPT, join(DATA, 'receipt.json')],
  [REGISTER, join(DATA, 'register.json')],
]) {
  if (!existsSync(join(ROOT, source))) fail(`missing ${source}`);
  await writeFile(target, await readFile(join(ROOT, source)));
  log(`wrote ${rel(target)} (copied from ${source})`);
}

// ---------------------------------------------------------------------------
// 4. Evidence — the derived facts behind the authored words in status.json.
// ---------------------------------------------------------------------------
const crateNames = (await readdir(join(ROOT, 'crates'))).sort();

const surfaces = SURFACES.map((surface) => {
  const backends = surface.backends.map((crate) => ({
    crate,
    exists: crateNames.includes(crate),
  }));

  const conformance = join(ROOT, surface.conformance);
  const conformanceFiles = existsSync(conformance)
    ? readdirSyncSafe(conformance).filter((name) => !name.endsWith('.json'))
    : [];

  return {
    id: surface.id,
    extension: surface.extension,
    name: surface.name,
    docs: statOrNull(surface.docs),
    example: statOrNull(surface.example),
    conformance: {
      path: surface.conformance,
      exists: existsSync(conformance),
      files: conformanceFiles.length,
    },
    golden: surface.golden ? statOrNull(surface.golden) : null,
    backends,
    status: backends.length > 0 ? 'implemented' : 'validated',
  };
});

function readdirSyncSafe(path) {
  try {
    return readdirSync(path);
  } catch {
    return [];
  }
}

const nodes = graph.nodes ?? [];
const edges = graph.edges ?? [];
const applications = graph.applications ?? [];

// `surfaces.json` is the one file the language pages read: the authored words
// from scripts/surfaces.mjs joined to the evidence computed above.
await writeJson(
  join(DATA, 'surfaces.json'),
  {
    formatVersion: 1,
    surfaces: SURFACES.map((surface, index) => {
      const evidence = surfaces[index];
      return {
        id: surface.id,
        extension: surface.extension,
        name: surface.name,
        tagline: surface.tagline,
        summary: surface.summary,
        docs: surface.docs,
        example: surface.example,
        status: evidence.status,
        backends: evidence.backends.filter((backend) => backend.exists).map((backend) => backend.crate),
        artifact: `artifacts/${surface.id}.json`,
        counts: {
          conformanceFiles: evidence.conformance.files,
        },
      };
    }),
  },
);

await writeJson(join(DATA, 'evidence.json'), {
  formatVersion: 1,
  generator: { binary: 'pherolang', version: reportedVersion, reported },
  counts: {
    surfaces: SURFACES.length,
    nodes: nodes.length,
    edges: edges.length,
    applications: applications.length,
    crates: crateNames.length,
  },
  applications: applications.map((application) => ({
    id: application.id,
    files: application.files ?? [],
  })),
  kinds: {
    nodes: countBy(nodes, 'kind'),
    edges: countBy(edges, 'kind'),
  },
  crates: crateNames,
  surfaces,
});

function countBy(items, key) {
  const counts = {};
  for (const item of items) {
    const value = item[key] ?? 'unknown';
    counts[value] = (counts[value] ?? 0) + 1;
  }
  return Object.fromEntries(Object.entries(counts).sort(([a], [b]) => a.localeCompare(b)));
}

// ---------------------------------------------------------------------------
// 5. Docs inventory — what the ingestion step will copy, and its title.
// ---------------------------------------------------------------------------
const docsDir = join(ROOT, 'docs');
const docsFiles = (await readdir(docsDir)).filter((name) => name.endsWith('.md')).sort();

const docs = [];
for (const name of docsFiles) {
  const path = join(docsDir, name);
  const text = await readFile(path, 'utf8');
  const lines = text.split('\n');
  const headingIndex = lines.findIndex((line) => line.startsWith('# '));
  const title = headingIndex >= 0 ? lines[headingIndex].slice(2).trim() : name.replace(/\.md$/, '');
  const firstParagraph =
    lines
      .slice(headingIndex + 1)
      .find((line) => line.trim().length > 0 && !line.startsWith('#') && !line.startsWith('|')) ?? '';

  docs.push({
    path: rel(path),
    name,
    slug: name === 'README.md' ? 'index' : name.replace(/\.md$/, '').toLowerCase(),
    title,
    description: firstParagraph.trim().replace(/[[\]]/g, ''),
    bytes: Buffer.byteLength(text, 'utf8'),
    lines: lines.length,
  });
}

await writeJson(join(DATA, 'docs-inventory.json'), {
  formatVersion: 1,
  docs,
});

// ---------------------------------------------------------------------------
// 6. The demo projection (owned by scripts/render-graph.mjs).
// ---------------------------------------------------------------------------
const renderGraph = join(SITE, 'scripts', 'render-graph.mjs');
if (existsSync(renderGraph)) {
  log('running scripts/render-graph.mjs');
  execFileSync(process.execPath, [renderGraph], { cwd: SITE, stdio: 'inherit' });
} else {
  log('scripts/render-graph.mjs not present — skipping support-model.json');
}

log('done');
