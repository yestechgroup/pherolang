import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import test from 'node:test';

import { findRepoRoot } from '../../packages/highlighting/src/artifact.mjs';

const root = findRepoRoot();
const read = (relative) => readFileSync(join(root, relative), 'utf8');

function workspaceVersion() {
  const manifest = read('Cargo.toml');
  const workspace = manifest.split('[workspace.package]')[1] ?? '';
  const match = /^\s*version\s*=\s*"([^"]+)"/m.exec(workspace);
  assert.ok(match, 'Cargo.toml declares a [workspace.package] version');
  return match[1];
}

test('the committed highlight artifact was generated by the workspace version', () => {
  const artifact = JSON.parse(read('site/data/highlighting/spans.json'));
  assert.equal(
    artifact.generator?.version,
    workspaceVersion(),
    'a version bump must regenerate site/data/highlighting/spans.json',
  );
});

test('the release workflow checks the highlight and grammar contract', () => {
  const workflow = read('.github/workflows/release.yml');
  assert.match(
    workflow,
    /highlight --surface mox --format json -/,
    'the release workflow must prove the shipped binary exposes `pherolang highlight`',
  );
  assert.match(workflow, /grammar --out/, 'the release workflow must generate the grammar package');
  assert.match(workflow, /grammar --check/, 'the release workflow must byte-check the generated package');
});

test('the 0.4.0 runbook names the tag, the highlight contract and the source fallback', () => {
  const runbook = read('docs/RELEASE-0.4.0.md');
  for (const phrase of [
    'v0.4.0',
    'pherolang highlight',
    'git tag',
    'grammar --check',
    'source build',
    'PHEROLANG_VERSION',
  ]) {
    assert.ok(runbook.includes(phrase), `docs/RELEASE-0.4.0.md is missing ${JSON.stringify(phrase)}`);
  }
});
